#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# install.sh
# Run this from the root of any project to install the AIDLC harness.
# It copies the ai/ scaffold into your project and creates the aidlc
# entrypoint script.
#
# Usage:
#   /path/to/aidlc/install.sh
#
# Options:
#   --force    Overwrite existing ai/ folder (use with caution)
# -----------------------------------------------------------------------------

set -euo pipefail

AIDLC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET_DIR="$(pwd)"
FORCE=false

# Parse flags
for arg in "$@"; do
  case $arg in
    --force) FORCE=true ;;
    *) echo "Unknown option: $arg"; exit 1 ;;
  esac
done

echo ""
echo "  ╔═══════════════════════════════════════╗"
echo "  ║   AIDLC — AI Development Life Cycle   ║"
echo "  ╚═══════════════════════════════════════╝"
echo ""
echo "  Installing into: $TARGET_DIR"
echo ""

# ---------- guard ------------------------------------------------------------

if [[ -d "$TARGET_DIR/ai" ]] && [[ "$FORCE" == false ]]; then
  echo "[aidlc] ai/ folder already exists. Use --force to overwrite."
  exit 1
fi

# ---------- copy scaffold ----------------------------------------------------

echo "[aidlc] Copying ai/ scaffold..."
cp -r "$AIDLC_DIR/scaffold/ai" "$TARGET_DIR/ai"

echo "[aidlc] Creating aidlc entrypoint..."
cat > "$TARGET_DIR/aidlc" <<EOF
#!/usr/bin/env bash
# AIDLC entrypoint — generated by install.sh
# Do not edit manually.

AIDLC_HOME="$AIDLC_DIR"
COMMAND="\${1:-help}"
shift || true

case "\$COMMAND" in
  run)
    bash "\$AIDLC_HOME/core/engine/skill-runner.sh" "\$@"
    ;;
  list)
    echo "Available skills:"
    for d in ai/skills/*/; do
      skill=\$(basename "\$d")
      desc=\$(awk '/^---\$/{count++; next} count==1 && /^description:/{sub(/^description:\s*/,""); print; exit}' "\${d}SKILL.md" 2>/dev/null || echo "")
      printf "  %-24s %s\n" "\$skill" "\$desc"
    done
    ;;
  version)
    cat "\$AIDLC_HOME/VERSION"
    ;;
  help|*)
    echo "Usage: ./aidlc <command> [options]"
    echo ""
    echo "Commands:"
    echo "  run <skill> [--param value ...]   Run a skill"
    echo "  list                              List available skills"
    echo "  version                           Show harness version"
    echo ""
    echo "Examples:"
    echo "  ./aidlc run implement --requirement 'Add UserService with CRUD'"
    echo "  ./aidlc run review-code --file src/main/java/UserService.java"
    echo "  ./aidlc list"
    ;;
esac
EOF

chmod +x "$TARGET_DIR/aidlc"

echo "[aidlc] Adding aidlc to .gitignore (binary entrypoint)..."
if [[ -f "$TARGET_DIR/.gitignore" ]]; then
  if ! grep -q "^/aidlc$" "$TARGET_DIR/.gitignore" 2>/dev/null; then
    echo "" >> "$TARGET_DIR/.gitignore"
    echo "# AIDLC entrypoint (generated)" >> "$TARGET_DIR/.gitignore"
    echo "/aidlc" >> "$TARGET_DIR/.gitignore"
  fi
fi

AIDLC_VERSION=$(cat "$AIDLC_DIR/VERSION")

echo ""
echo "  ✅ AIDLC v${AIDLC_VERSION} installed successfully!"
echo ""
echo "  Next steps:"
echo "  1. Export your API key:  export ANTHROPIC_API_KEY=sk-ant-..."
echo "  2. Edit ai/rules/project-context.md with your project details"
echo "  3. Run a skill:          ./aidlc run implement --requirement 'Your task here'"
echo "  4. List all skills:      ./aidlc list"
echo ""
